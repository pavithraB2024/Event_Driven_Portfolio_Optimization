#!/usr/bin/env python3
"""Unified figure restyling for all manuscript plots (Figures 4–10, excluding TikZ 1–3).

Reads ONLY from saved CSVs — no model evaluation. Change FONT_SIZE or any
styling constant at the top, then run once to regenerate every figure.

First-time setup: each eval script must be run once to produce curve CSVs.
After that, this script handles all restyling without touching models.

Required CSVs (generated by eval scripts listed below):
  results/imputed_wealth_curves_28stocks.csv          ← evaluate_imputed_portfolio_v2.py
  results/gnn_sac_eval_details_28stocks.csv           ← evaluate_gnn_sac.py
  results/benchmark_wealth_curves_28stocks.csv        ← evaluate_gnn_sac.py
  results/crisis_wealth_curves_28stocks.csv           ← run_crisis_evaluation_gnn.py
  results/complexity_sweep_sp50_pit2013.csv           ← run_complexity_sweep.py
  results/gnn_sac_eval_details_sp50_pit2013_event_step5000.csv ← evaluate_gnn_sac.py
  results/xai_node_importance_28stocks.csv            ← perform_shap_selection.py
  simulations/backtesting_results/sp50_pit2013/*/portfolio_values.csv ← run_baseline_backtests.py

Usage:
    source .venv/bin/activate
    python scripts/visualization/restyle_all_figures.py          # all figures
    python scripts/visualization/restyle_all_figures.py --only 7 # single figure
"""
