def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--only', type=int, nargs='+',
                        help='Only restyle specific figure numbers (e.g. --only 7 8)')
    args = parser.parse_args()

    targets = args.only if args.only else sorted(FIGURES.keys())

    print("=" * 60)
    print(f"Restyling manuscript figures (FONT_SIZE={FONT_SIZE})")
    print("=" * 60)

    generated = []
    skipped = []
    for num in targets:
        if num not in FIGURES:
            print(f"\n[WARN] Figure {num} not in registry (valid: {sorted(FIGURES.keys())})")
            continue
        desc, func, paper_name = FIGURES[num]
        print(f"\nFigure {num} ({desc}):")
        eps = func()
        copy_to_paper(eps, paper_name)
        (generated if eps else skipped).append(num)

    print("\n" + "=" * 60)
    print(f"Generated: {len(generated)} figures ({', '.join(map(str, generated))})")
    if skipped:
        print(f"Skipped: {len(skipped)} figures (run eval scripts first to generate curve CSVs):")
        for n in skipped:
            print(f"  Figure {n}: see docstring for required CSV")
    print("=" * 60)


if __name__ == "__main__":
    main()
